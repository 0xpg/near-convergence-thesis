 c.simple_pair AND (i.asset_id IS NULL OR o.asset_id IS NULL) AS unknown_asset_pair
 FROM canonical c LEFT JOIN asset_registry i ON c.input_asset=i.asset_id AND c.simple_pair
 LEFT JOIN asset_registry o ON c.output_asset=o.asset_id AND c.simple_pair
)
 , grouped_pairs AS (
SELECT input_asset,output_asset,input_representation_chain,output_representation_chain,input_symbol,output_symbol,
