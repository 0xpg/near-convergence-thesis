 CASE WHEN c.simple_pair THEN c.output_asset ELSE '(multi-or-one-sided)' END AS output_asset,
 CASE WHEN c.simple_pair THEN coalesce(i.representation_chain,'Unknown representation') ELSE 'Not a simple pair' END AS input_representation_chain,
 CASE WHEN c.simple_pair THEN coalesce(o.representation_chain,'Unknown representation') ELSE 'Not a simple pair' END AS output_representation_chain,
 CASE WHEN c.simple_pair THEN coalesce(i.symbol,'Unknown asset') ELSE 'Multiple assets' END AS input_symbol,
 CASE WHEN c.simple_pair THEN coalesce(o.symbol,'Unknown asset') ELSE 'Multiple assets' END AS output_symbol,
