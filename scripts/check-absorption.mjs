import assert from 'node:assert/strict';
import {createParticles,particleAt,startAbsorption} from '../src/overview/absorption.mjs';
const points=createParticles();
assert.equal(points.length,1796);
assert.deepEqual(points,createParticles());
assert.throws(()=>createParticles(3));
const stream=points.find(p=>p.stream&&!p.core);
for(let mode=0;mode<3;mode++)for(let time=0;time<24;time+=.2)for(const p of createParticles(mode)){
  const at=particleAt(p,time,mode,p.sector);
  assert(Number.isFinite(at.x)&&Number.isFinite(at.y)&&at.alpha>=0&&at.alpha<=1);
  assert(Math.hypot(at.x-320,at.y-320)<300);
}
const distances=Array.from({length:80},(_,i)=>{const at=particleAt(stream,i/10,0,stream.sector);return Math.hypot(at.x-320,at.y-320);});
assert(Math.max(...distances)-Math.min(...distances)>100,'Particles must travel inward, not only fade');
assert.notDeepEqual(particleAt(stream,2,0,stream.sector),particleAt(stream,2,1,stream.sector));
assert(createParticles(1)[0].r>points[0].r,'Tidal needs a wider ring without enlarging its individual tiles');
console.log('1,796 deterministic tiles: finite bounded positions, real inward travel and distinct motion directions passed.');
globalThis.matchMedia=()=>({matches:true,addEventListener(){},removeEventListener(){}});
globalThis.document={hidden:false,addEventListener(){},removeEventListener(){}};
globalThis.ResizeObserver=class{observe(){}disconnect(){}};
globalThis.cancelAnimationFrame=()=>{};
globalThis.devicePixelRatio=1;
const handlers=new Map(),context=Object.fromEntries(['clearRect','save','translate','scale','fillRect','restore','setTransform'].map(name=>[name,()=>{}]));
const canvas={dataset:{},getContext:()=>context,getBoundingClientRect:()=>({width:640,height:640,left:0,top:0}),addEventListener:(name,handler)=>handlers.set(name,handler),removeEventListener:name=>handlers.delete(name)};
let chosen;
const scene=startAbsorption(canvas,1,index=>chosen=index);
assert.equal(canvas.dataset.direction,'1');
scene.select(1);assert.equal(canvas.dataset.direction,'2');assert.equal(chosen,1);
handlers.get('pointerleave')();assert.equal(canvas.dataset.selected,'-1','Leaving restores the overview');
handlers.get('pointerdown')({clientX:320,clientY:80,pointerType:'touch'});assert.equal(canvas.dataset.direction,'2');assert.equal(chosen,0);
handlers.get('pointerup')({pointerType:'touch'});assert.equal(canvas.dataset.direction,'2','Touch selection stays open after release');
handlers.get('pointerleave')();assert.equal(chosen,0,'Pinned category survives leaving');
handlers.get('pointermove')({clientX:550,clientY:320,pointerType:'mouse'});assert.equal(chosen,0,'Hover cannot replace a pinned selection');
scene.select(2,true);assert.equal(chosen,2,'Selecting another category replaces the pin');
scene.select(-1,true);assert.equal(canvas.dataset.direction,'1');
handlers.get('pointermove')({clientX:550,clientY:320,pointerType:'mouse'});assert.equal(canvas.dataset.direction,'2');
assert(!handlers.has('click'),'Pointer focus must not depend on a click');
scene.select(-1);assert.equal(canvas.dataset.direction,'1');assert.equal(chosen,-1);
scene.select(7,true);assert.equal(chosen,7,'Additional research categories are selectable');
assert.throws(()=>scene.select(8));
scene.destroy();assert.equal(handlers.size,0);
const stationary=createParticles(1).filter(p=>!p.stream);
for(const p of stationary)assert.deepEqual(particleAt(p,0,1),particleAt(p,5,1),'Cluster anchors must remain still');
console.log('Hover and immediate touch focus, persistent selection, explicit reset, stationary cluster anchors, invalid categories and cleanup passed.');
